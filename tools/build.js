/* Build js/levels.js and js/daily.js from tools/levels-src.js + generated pools.
 * Every level is re-solved here: the build fails if any level has no solution,
 * and the stored hint solution is always one the simulator replays successfully. */
'use strict';
const fs = require('fs');
const path = require('path');
const Sim = require('../js/sim.js');
const { solve } = require('./solver.js');
const SRC = require('./levels-src.js');

const POOL_DIR = path.join(__dirname, 'pool');
const pools = {};
function pool(name) {
  if (!pools[name]) {
    const f = path.join(POOL_DIR, name + '.json');
    pools[name] = fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : [];
    pools[name].sort((a, b) => a.stats.diff - b.stats.diff || a.stats.solutions - b.stats.solutions);
  }
  return pools[name];
}
const used = new Set();
function keyOf(def) { return def.map.join('/') + '|' + def.goal.join('/') + '|' + def.inks.join(','); }

function pickFrom(name, at) {
  let p = pool(name).filter(e => e.stats.distinct > 0);
  if (!p.length && process.env.DRAFT) { console.warn('DRAFT: empty pool ' + name + ', using c5_ryb'); p = pool('c5_ryb').filter(e => e.stats.distinct > 0); }
  if (!p.length) throw new Error('empty pool ' + name);
  let idx = Math.round(at * (p.length - 1));
  for (let d = 0; d < p.length; d++) {
    for (const j of [idx + d, idx - d]) {
      if (j < 0 || j >= p.length) continue;
      if (!used.has(keyOf(p[j].def))) { used.add(keyOf(p[j].def)); return p[j]; }
    }
  }
  throw new Error('pool exhausted ' + name);
}

function verify(def, label) {
  const L = Sim.parse(def);
  const r = solve(def, { cap: 200000, leafCap: 3e7 });
  if (!r.solutions) throw new Error(label + ': NO SOLUTION');
  let sol = def.sol;
  if (sol) {
    const run = Sim.run(L, sol);
    if (!run.ok) { console.warn(label + ': stored solution failed (' + run.error + '), using solver'); sol = null; }
  }
  if (!sol) sol = r.best.map(d => ({ x: d.x, y: d.y, t: d.t }));
  const run2 = Sim.run(L, sol);
  if (!run2.ok) throw new Error(label + ': canonical solution does not replay');
  const sameBeat = sol.some((d, k) => k > 0 && d.t === sol[k - 1].t);
  return { sol, stats: { solutions: r.solutions, distinct: r.distinctOnly, leaves: r.leaves, firstCells: r.firstCells, sameBeat, aborted: r.aborted } };
}

function ascii(def) {
  const L = Sim.parse(def), run = Sim.run(L, def.sol), out = [];
  for (let y = 0; y < L.h; y++) {
    let s = '';
    for (let x = 0; x < L.w; x++) { const i = y * L.w + x; s += L.terrain[i] === 1 ? '#' : (run.state.col[i] ? Sim.NAME[run.state.col[i]] : '.'); }
    out.push('    ' + def.map[y] + '   ' + (def.goal ? def.goal[y] : '') + '   ' + s);
  }
  return out.join('\n');
}

const report = [];
const chapters = SRC.chapters.map((ch, ci) => {
  const levels = ch.slots.map((slot, li) => {
    let def, src;
    if (slot.pick) {
      const e = pickFrom(slot.pick, slot.at);
      def = JSON.parse(JSON.stringify(e.def));
      src = slot.pick + '#' + e.seed;
    } else {
      def = JSON.parse(JSON.stringify(slot));
      src = 'hand';
      used.add(keyOf(def));
    }
    const id = slot.id || (ch.id + '-' + (li + 1));
    const label = (ci + 1) + '-' + (li + 1) + ' ' + id;
    const v = verify(def, label);
    const name = { ko: ch.names[li][0], en: ch.names[li][1] };
    const out = { id, name, map: def.map, goal: def.goal, inks: def.inks, sol: v.sol, tempo: slot.tempo || ch.tempo };
    if (slot.intro) out.intro = slot.intro;
    if (slot.tapCue) out.tapCue = true;
    report.push(`${label} [${src}] inks=${def.inks.join(',')} sols=${v.stats.solutions} distinct=${v.stats.distinct} first=${v.stats.firstCells} sameBeat=${v.stats.sameBeat} plan=${JSON.stringify(v.sol.map(d => [d.x, d.y, d.t]))}\n` + ascii(out));
    return out;
  });
  return { id: ch.id, name: ch.name, desc: ch.desc, paper: ch.paper, levels };
});

// ---- daily pool ----
const daily = [];
for (const name of SRC.daily) for (const e of pool(name)) {
  if (!e.stats.distinct) continue;
  const def = e.def;
  const L = Sim.parse(def);
  if (!Sim.run(L, def.sol).ok) continue;
  daily.push({ map: def.map, goal: def.goal, inks: def.inks, sol: def.sol, d: e.stats.diff + def.inks.length * 2 + (def.goal.join('').replace(/\./g, '').length) * 0.2 });
}
daily.sort((a, b) => a.d - b.d);
daily.forEach((e, k) => { e.tier = Math.min(2, Math.floor(k * 3 / daily.length)); delete e.d; });

const header = '/* Generated by tools/build.js - do not edit by hand. */\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'levels.js'), header + 'window.INK_LEVELS = ' + JSON.stringify({ chapters }) + ';\n');
const dailyCode = fs.readFileSync(path.join(__dirname, 'daily-template.js'), 'utf8').replace('/*POOL*/[]', JSON.stringify(daily));
fs.writeFileSync(path.join(__dirname, '..', 'js', 'daily.js'), header + dailyCode);
fs.writeFileSync(path.join(__dirname, 'build-report.txt'), report.join('\n') + '\n');
console.log('levels:', chapters.reduce((n, c) => n + c.levels.length, 0), 'daily pool:', daily.length, 'tiers:', [0, 1, 2].map(t => daily.filter(d => d.tier === t).length).join('/'));
